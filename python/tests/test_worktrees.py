"""`gds issue start` makes the branch and worktree before the agent gets the work (kit issue #107), on real git
repositories in a temporary folder; only `pre-commit install` is replaced by a stand-in that writes the hook files."""

from __future__ import annotations

import json
import os
import shutil
import subprocess
from pathlib import Path

import pytest
from test_issues import REPO, FakeGh

from gds_tools import issues, worktrees
from gds_tools.worktrees import WorktreeError


def git(cwd: Path, *args: str) -> str:
    done = subprocess.run(
        ["git", "-C", str(cwd), "-c", "user.email=a@example.org", "-c", "user.name=t", *args],
        capture_output=True,
        text=True,
        check=True,
    )
    return done.stdout.strip()


@pytest.fixture
def world(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> dict[str, Path]:
    """A remote with one commit (a pre-commit config in it), a checkout under repos/ and an empty worktrees/."""
    for key, value in (
        ("NAME", "t"),
        ("EMAIL", "a@example.org"),
    ):  # the code under test commits as the user: CI has none
        monkeypatch.setenv(f"GIT_AUTHOR_{key}", value)
        monkeypatch.setenv(f"GIT_COMMITTER_{key}", value)
    origin, root = tmp_path / "origin.git", tmp_path / "ws"
    subprocess.run(["git", "init", "-q", "--bare", "-b", "main", str(origin)], check=True)
    seed = tmp_path / "seed"
    seed.mkdir()
    git(seed, "init", "-q", "-b", "main")
    (seed / ".pre-commit-config.yaml").write_text("repos: []\n", encoding="utf-8")
    git(seed, "add", "-A")
    git(seed, "commit", "-q", "-m", "build: Add a config")
    git(seed, "remote", "add", "origin", str(origin))
    git(seed, "push", "-q", "origin", "main")
    (root / "repos").mkdir(parents=True)
    (root / "worktrees").mkdir()
    subprocess.run(["git", "clone", "-q", str(origin), str(root / "repos" / "deadnight")], check=True)
    return {"root": root, "seed": seed, "checkout": root / "repos" / "deadnight", "worktrees": root / "worktrees"}


def write_hook(path: Path, text: str) -> None:
    """A hook git will run: LF line endings and the executable bit (git ignores a hook without it)."""
    path.write_text(text, encoding="utf-8", newline="\n")
    path.chmod(0o755)


def fake_install(worktree: Path) -> None:
    folder = worktrees.hooks_dir(worktree)
    folder.mkdir(parents=True, exist_ok=True)
    for kind in worktrees.HOOK_TYPES:
        write_hook(folder / kind, "#!/bin/sh\n# File generated by pre-commit\n")


def make(world, title="net: Add the lobby list", number=7, **kwargs):
    return worktrees.create(world["checkout"], world["worktrees"] / "deadnight", title, number, **kwargs)


def test_branch_names_come_from_the_title():
    name = worktrees.branch_name("tools: Add worktree setup to gds issue start", 107)
    cut = worktrees.branch_name("tools: Add worktree setup to gds issue start and a pre-push check", 107)
    assert cut == "tools-add-worktree-setup-to-gds-issue-start-and"  # cut at a word boundary
    assert name == "tools-add-worktree-setup-to-gds-issue-start"
    assert worktrees.branch_name("net: Fix it", 9, taken={"net-fix-it"}) == "net-fix-it-9"
    assert worktrees.branch_name("???", 5) == "issue-5"
    assert len(worktrees.branch_name("x " * 80, 1)) <= 48


def test_create_makes_the_worktree_from_fresh_origin_main_at_an_absolute_path(world):
    git(world["seed"], "commit", "-q", "--allow-empty", "-m", "build: Add a later commit")
    git(world["seed"], "push", "-q", "origin", "main")  # the checkout has not fetched this yet
    made = make(world, install=fake_install)
    assert made.path == (world["worktrees"] / "deadnight" / "net-add-the-lobby-list").resolve()
    assert made.path.is_absolute() and made.branch == "net-add-the-lobby-list"
    assert git(made.path, "rev-parse", "HEAD") == git(world["seed"], "rev-parse", "HEAD") == made.base
    assert git(made.path, "rev-parse", "--abbrev-ref", "HEAD") == "net-add-the-lobby-list"
    upstream = subprocess.run(
        ["git", "-C", str(made.path), "rev-parse", "--abbrev-ref", "@{upstream}"], capture_output=True, text=True
    )
    assert upstream.returncode != 0  # not tracking origin/main: a push goes to the branch of its own name
    assert any("installing them" in line for line in made.hooks) and "installed" in made.hooks[-1]
    assert worktrees.missing_hooks(made.path) == []


def test_hooks_that_are_already_installed_are_not_installed_again(world):
    fake_install(world["checkout"])
    calls = []
    made = make(world, install=calls.append)
    assert calls == [] and len(made.hooks) == 1 and "installed" in made.hooks[0]


def test_a_stale_hook_set_without_pre_push_is_completed(world):
    fake_install(world["checkout"])
    (worktrees.hooks_dir(world["checkout"]) / "pre-push").unlink()
    assert worktrees.missing_hooks(world["checkout"]) == ["pre-push"]
    made = make(world, install=fake_install)
    assert worktrees.missing_hooks(made.path) == []


def test_a_pre_push_hook_that_dies_is_found_at_the_start_not_at_the_first_push(world):
    def broken(worktree: Path) -> None:
        fake_install(worktree)
        write_hook(
            worktrees.hooks_dir(worktree) / "pre-push",
            "#!/bin/sh\n# File generated by pre-commit\necho boom >&2\nexit 7\n",
        )

    with pytest.raises(WorktreeError, match="pre-push hook does not run"):
        make(world, install=broken)
    assert not (world["worktrees"] / "deadnight" / "net-add-the-lobby-list").exists()


@pytest.mark.skipif(os.name != "nt", reason="pre-commit cannot find /bin/sh only on Windows")
def test_a_git_lfs_pre_push_that_pre_commit_moved_aside_is_made_runnable(tmp_path):
    legacy = tmp_path / "pre-push.legacy"
    legacy.write_bytes(b'#!/bin/sh\ngit lfs pre-push "$@"\n')
    assert worktrees.repair_legacy_hooks(tmp_path) == ["pre-push.legacy"]
    assert legacy.read_bytes() == b'#!/usr/bin/env sh\ngit lfs pre-push "$@"\n'
    assert worktrees.repair_legacy_hooks(tmp_path) == []


def test_a_repository_without_a_pre_commit_config_needs_no_hooks(world):
    git(world["seed"], "rm", "-q", ".pre-commit-config.yaml")
    git(world["seed"], "commit", "-q", "-m", "build: Remove the config")
    git(world["seed"], "push", "-q", "origin", "main")
    made = make(world)
    assert "no .pre-commit-config.yaml" in made.hooks[0]


def test_hooks_that_cannot_be_installed_leave_nothing_behind(world):
    with pytest.raises(WorktreeError, match="still not installed"):
        make(world, install=lambda path: None)
    assert not (world["worktrees"] / "deadnight" / "net-add-the-lobby-list").exists()
    assert "net-add-the-lobby-list" not in git(world["checkout"], "branch", "--list")


def test_an_install_that_fails_is_reported_and_cleaned_up(world):
    def broken(path: Path) -> None:
        raise WorktreeError("`pre-commit install` failed: no network")

    with pytest.raises(WorktreeError, match="cannot be installed.*no network"):
        make(world, install=broken)
    assert not (world["worktrees"] / "deadnight" / "net-add-the-lobby-list").exists()


def test_an_existing_branch_or_folder_is_refused_without_changes(world):
    git(world["checkout"], "branch", "mine")
    with pytest.raises(WorktreeError, match="already exists"):
        make(world, branch="mine", install=fake_install)
    (world["worktrees"] / "deadnight" / "taken").mkdir(parents=True)
    with pytest.raises(WorktreeError, match="already exists"):
        make(world, branch="taken", install=fake_install)
    # a title whose branch is taken gets the issue number instead of failing
    git(world["checkout"], "branch", "net-add-the-lobby-list")
    assert make(world, install=fake_install).branch == "net-add-the-lobby-list-7"


def test_a_folder_that_is_not_a_checkout_is_refused(world, tmp_path):
    with pytest.raises(WorktreeError, match="not a git checkout"):
        worktrees.create(tmp_path / "nowhere", world["worktrees"] / "x", "t", 1)


# --- the start command -------------------------------------------------------------------------------------------


def prepared_for(world):
    def prepare(issue):
        made = worktrees.create(
            world["checkout"], world["worktrees"] / "deadnight", issue.title, issue.number, install=fake_install
        )
        return issues.Prepared(
            made.branch,
            made.path.as_posix(),
            ["worktree " + made.path.as_posix()],
            lambda: worktrees.remove(world["checkout"], made.path, made.branch),
        )

    return prepare


def test_start_records_the_worktree_and_prints_it_for_the_prompt(world, tmp_path):
    ledger = tmp_path / "cache" / "issues-started.json"
    lines = issues.start(REPO, 156, "godot-1", gh=FakeGh(), ledger=ledger, prepare=prepared_for(world))
    entry = json.loads(ledger.read_text(encoding="utf-8"))["started"]["ryubara/deadnight#156"]
    assert entry["worktree"].endswith("/worktrees/deadnight/" + entry["branch"]) and Path(entry["worktree"]).is_dir()
    assert lines[-2] == f"Worktree: {entry['worktree']}" and lines[-1] == "Issue: Ryubara/deadnight#156"
    assert any(line.startswith("worktree ") for line in lines)


def test_a_worktree_that_cannot_be_made_leaves_the_issue_untouched(tmp_path):
    gh, ledger = FakeGh(), tmp_path / "cache" / "issues-started.json"

    def prepare(issue):
        raise issues.IssueError("deadnight#156 was not started: no checkout")

    with pytest.raises(issues.IssueError, match="no checkout"):
        issues.start(REPO, 156, "a", gh=gh, ledger=ledger, prepare=prepare)
    assert gh.calls == [] and not ledger.exists()


def test_a_github_failure_after_the_worktree_takes_the_worktree_away(world, tmp_path):
    class Failing(FakeGh):
        def __call__(self, args):
            if args[:2] == ["issue", "comment"]:
                raise issues.IssueError("gh failed")
            return super().__call__(args)

    ledger = tmp_path / "cache" / "issues-started.json"
    with pytest.raises(issues.IssueError, match="gh failed"):
        issues.start(REPO, 156, "a", gh=Failing(), ledger=ledger, prepare=prepared_for(world))
    assert list((world["worktrees"] / "deadnight").iterdir()) == []
    assert not ledger.exists()


@pytest.mark.skipif(not (shutil.which("pre-commit") or shutil.which("uvx")), reason="needs pre-commit or uvx")
def test_the_real_pre_commit_installs_all_three_hooks(world):
    """No stand-in: the three hook types of the kit's own config are written by pre-commit itself."""
    kit_config = Path(__file__).resolve().parents[2] / worktrees.CONFIG
    (world["checkout"] / worktrees.CONFIG).write_text(kit_config.read_text(encoding="utf-8"), encoding="utf-8")
    git(world["checkout"], "add", "-A")
    git(world["checkout"], "commit", "-q", "-m", "build: Use the kit config")
    git(world["checkout"], "push", "-q", "origin", "main")
    lfs = worktrees.hooks_dir(world["checkout"]) / "pre-push"  # Git LFS writes this one when a repository is cloned
    write_hook(lfs, "#!/bin/sh\nexit 0\n")
    made = make(world)  # runs the pre-push hook, which runs the moved-aside one
    assert worktrees.missing_hooks(made.path) == []
    assert "installing them" in made.hooks[0] and "pre-push hook runs" in made.hooks[-1]
    assert (worktrees.hooks_dir(made.path) / "pre-push.legacy").is_file()


# --- gds merge-main ------------------------------------------------------------------------------------------------

TRAILER = "Co-Authored-By: Claude Sonnet 5.5 <noreply@anthropic.com>"


def work_branch(world, name="work"):
    """A worktree on a branch with one commit (carrying the trailer), plus a later commit on origin/main."""
    made = make(world, title=name, number=1, install=fake_install)
    (made.path / "mine.txt").write_text("mine\n", encoding="utf-8")
    git(made.path, "add", "-A")
    git(made.path, "commit", "-q", "--no-verify", "-m", f"net: Add mine\n\n{TRAILER}")
    return made


def push_to_main(world, name: str, text: str) -> None:
    (world["seed"] / name).write_text(text, encoding="utf-8")
    git(world["seed"], "add", "-A")
    git(world["seed"], "commit", "-q", "-m", f"build: Add {name}")
    git(world["seed"], "push", "-q", "origin", "main")


def test_merge_main_commits_a_clean_merge_ending_in_the_one_trailer(world):
    made = work_branch(world)
    push_to_main(world, "other.txt", "other\n")
    lines = worktrees.merge_main(made.path)
    assert "merged origin/main" in lines[0]
    message = git(made.path, "log", "-1", "--format=%B")
    assert message == f"Merge origin/main into work\n\n{TRAILER}"
    assert len(git(made.path, "log", "-1", "--format=%P").split()) == 2  # a merge commit


def test_merge_main_with_nothing_new_changes_nothing(world):
    made = work_branch(world)
    head = git(made.path, "rev-parse", "HEAD")
    assert "nothing to merge" in worktrees.merge_main(made.path)[0]
    assert git(made.path, "rev-parse", "HEAD") == head


def test_merge_main_stops_on_conflicts_lists_the_files_and_continues_clean(world):
    made = work_branch(world)
    (made.path / "same.txt").write_text("mine\n", encoding="utf-8")
    git(made.path, "add", "-A")
    git(made.path, "commit", "-q", "--no-verify", "-m", f"net: Add same\n\n{TRAILER}")
    push_to_main(world, "same.txt", "theirs\n")
    with pytest.raises(worktrees.MergeConflict) as error:
        worktrees.merge_main(made.path, co_author="Claude Sonnet 5.5 <noreply@anthropic.com>")
    assert "same.txt" in str(error.value) and "--continue" in str(error.value)
    with pytest.raises(WorktreeError, match="already in progress"):
        worktrees.merge_main(made.path)
    with pytest.raises(worktrees.MergeConflict, match="still unmerged"):
        worktrees.merge_main(made.path, resume=True)
    (made.path / "same.txt").write_text("resolved\n", encoding="utf-8")
    git(made.path, "add", "same.txt")
    worktrees.merge_main(made.path, resume=True)
    message = git(made.path, "log", "-1", "--format=%B")
    assert message == f"Merge origin/main into work\n\n{TRAILER}" and "Conflicts" not in message


def test_merge_main_needs_a_trailer_a_clean_tree_and_a_work_branch(world):
    made = make(world, title="bare", number=2, install=fake_install)
    push_to_main(world, "other.txt", "other\n")
    with pytest.raises(WorktreeError, match="no Co-Authored-By trailer"):
        worktrees.merge_main(made.path)
    (made.path / "stray.txt").write_text("x\n", encoding="utf-8")
    git(made.path, "add", "stray.txt")
    with pytest.raises(WorktreeError, match="uncommitted changes"):
        worktrees.merge_main(made.path)
    with pytest.raises(WorktreeError, match="no merge is in progress"):
        worktrees.merge_main(made.path, resume=True)
    with pytest.raises(WorktreeError, match="merge main into a work branch"):
        worktrees.merge_main(world["checkout"])
